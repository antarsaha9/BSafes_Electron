const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('desktopAPI', {
  node: () => process.versions.node,
  chrome: () => process.versions.chrome,
  electron: () => process.versions.electron,
  // we can also expose variables, not just functions
  ping: () => ipcRenderer.invoke('ping'),
  addAMemberIfNotExists: (authId, member) => ipcRenderer.invoke('addAMemberIfNotExists', authId, member),
  addAnItemVersion: (memberId, key, itemVersion) => ipcRenderer.invoke('addAnItemVersion', memberId, key, itemVersion),
  addItemKeys: (itemList) => ipcRenderer.invoke('addItemKeys', itemList),
  failedDownloadingObjectsForAnItem: (id, version) => ipcRenderer.invoke('failedDownloadingObjectsForAnItem', id, version),
  finishedDownloadingObjectsForAnItem: (id, version) => ipcRenderer.invoke('finishedDownloadingObjectsForAnItem', id, version),
  getAMmberByAuthId: (authId) => ipcRenderer.invoke('getAMmberByAuthId', authId),
  getAnItemForDownloadingObjects: (workspace)=> ipcRenderer.invoke('getAnItemForDownloadingObjects', workspace),
  getAnItemKeyForDwonload: (memberId)=> ipcRenderer.invoke('getAnItemKeyForDwonload', memberId),
  getItemKeysForDownload: (memberId) => ipcRenderer.invoke('getItemKeysForDownload', memberId),
  getLastItemKey: (memberId) => ipcRenderer.invoke('getLastItemKey', memberId),
  getPageItem: (payload) => ipcRenderer.invoke('getPageItem', payload),
  getS3Object: (s3Key) => ipcRenderer.invoke('getS3Object', s3Key),
  isS3ObjectExisted: (s3Key) => ipcRenderer.invoke('isS3ObjectExisted', s3Key),
  listItems: (body) => ipcRenderer.invoke('listItems', body),
  putS3Object: (s3Key, data) => ipcRenderer.invoke('putS3Object', s3Key, data),
  updateMemberLastUpdatedTime: (authId, lastUpdatedTime) => ipcRenderer.invoke('updateMemberLastUpdatedTime', authId, lastUpdatedTime),
  // Export / Open Export: file data is passed as Uint8Array in both directions.
  chooseExportFolder: (options) => ipcRenderer.invoke('export:chooseFolder', options),
  checkExportFolder: (path, options) => ipcRenderer.invoke('export:checkFolder', path, options),
  writeExportFile: (rootPath, relPath, data) => ipcRenderer.invoke('export:writeFile', rootPath, relPath, data),
  beginExportFile: (rootPath, relPath) => ipcRenderer.invoke('export:beginFile', rootPath, relPath),
  appendExportFile: (fileId, data) => ipcRenderer.invoke('export:appendFile', fileId, data),
  finishExportFile: (fileId) => ipcRenderer.invoke('export:finishFile', fileId),
  abortExportFile: (fileId) => ipcRenderer.invoke('export:abortFile', fileId),
  readExportFile: (rootPath, relPath) => ipcRenderer.invoke('export:readFile', rootPath, relPath),
  showExportFolder: (path) => ipcRenderer.invoke('export:showFolder', path),
  hashExportFile: (rootPath, relPath, expectedSize) => ipcRenderer.invoke('export:hashFile', rootPath, relPath, expectedSize),
  listExportFolder: (rootPath, relPath) => ipcRenderer.invoke('export:listFolder', rootPath, relPath),
  removeExportEntry: (rootPath, relPath) => ipcRenderer.invoke('export:removeEntry', rootPath, relPath),
  openExportInBrowser: (rootPath) => ipcRenderer.invoke('export:openInBrowser', rootPath),
  linkExportFile: (rootPath, fromRelPath, toRelPath) => ipcRenderer.invoke('export:linkFile', rootPath, fromRelPath, toRelPath),
  hideExportEntry: (rootPath, relPath) => ipcRenderer.invoke('export:hideEntry', rootPath, relPath),
})